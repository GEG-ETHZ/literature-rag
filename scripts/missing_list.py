"""Render docs/missing-papers/still_to_get.csv as a Markdown checklist of clickable links.

Usage:
    uv run python scripts/missing_list.py docs/missing-papers/still_to_get.csv \
        docs/missing-papers/PAPERS_TO_GET.md
"""

import argparse
import csv
import datetime
import sys
import urllib.parse
from collections.abc import Sequence
from pathlib import Path

GROUPS: tuple[tuple[str, str], ...] = (
    ("paywalled", "Paywalled: open the link on the ETH network or VPN"),
    ("nodoi", "No DOI or link: search by title"),
    ("thesis", "Theses: ask the author or the ETH Library"),
)
SCHOLAR = "https://scholar.google.com/scholar?q="
REQUIRED = ("title", "reason")


def group_of(reason: str) -> str:
    """Return the group key for a row's failure reason."""
    reason = reason.lower()
    if "thesis" in reason:
        return "thesis"
    if "no doi" in reason:
        return "nodoi"
    return "paywalled"


def usable_link(url: str) -> str:
    """Return the link if it points at the paper, or an empty string for a placeholder."""
    url = url.strip()
    if url.startswith("10."):
        url = "https://doi.org/" + url
    if not url or "(none)" in url or "..." in url:
        return ""
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme not in ("http", "https") or parsed.path in ("", "/"):
        return ""
    return url


def _scholar(title: str) -> str:
    return SCHOLAR + urllib.parse.quote_plus(f'"{title}"')


def _target(url: str) -> str:
    """Wrap a URL so that parentheses or spaces in it do not end the Markdown link."""
    return f"<{url.replace(' ', '%20')}>"


def _year(row: dict[str, str]) -> str:
    return row["year"] or "n.d."


def _year_key(row: dict[str, str]) -> int:
    return int(row["year"]) if row["year"].isdigit() else 0


def _escape(title: str) -> str:
    return title.replace("[", "(").replace("]", ")").replace("|", "/")


def _line(row: dict[str, str]) -> str:
    link = usable_link(row["doi_or_link"])
    title = _escape(row["title"])
    head = f"[{title}]({_target(link)})" if link else f"[{title}]({_scholar(row['title'])})"
    scholar = f" · [Scholar]({_scholar(row['title'])})" if link else ""
    platform = f" · [platform]({_target(row['platform_url'])})" if row["platform_url"] else ""
    return f"- [ ] {_year(row)} · {head}{scholar}{platform} · {row['type']}"


def render(rows: Sequence[dict[str, str]], today: str) -> str:
    """Return the Markdown checklist for the given rows."""
    lines = [
        "# GEG own papers still to get",
        "",
        f"{len(rows)} GEG-own papers on geg.ethz.ch whose PDF the literature RAG does not have yet. "
        "How to help: [README.md](README.md) in this folder.",
        "",
        f"Updated {today} from `still_to_get.csv`. Do not edit this file by hand; edit the CSV and run "
        "`scripts/missing_list.py`.",
        "",
    ]
    for key, heading in GROUPS:
        items = sorted(
            (r for r in rows if group_of(r["reason"]) == key),
            key=lambda r: (-_year_key(r), r["title"]),
        )
        if not items:
            continue
        lines += [f"## {heading} ({len(items)})", "", *(_line(r) for r in items), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def _clean(raw: dict[str | None, str | None]) -> dict[str, str]:
    """Turn a DictReader row into plain strings; missing trailing cells become empty."""
    return {key: (value or "").strip() for key, value in raw.items() if key is not None}


def _problems(rows: Sequence[dict[str, str]]) -> list[str]:
    """Return one message per row that lacks a required field; row 1 is the header."""
    return [
        f"row {number}: missing {', '.join(f for f in REQUIRED if not row.get(f))}"
        for number, row in enumerate(rows, start=2)
        if any(not row.get(f) for f in REQUIRED)
    ]


def main(argv: Sequence[str] | None = None) -> int:
    """Read the CSV, write the checklist, return the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("csv", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--date", default=datetime.date.today().isoformat())
    args = parser.parse_args(argv)
    with args.csv.open(newline="", encoding="utf-8-sig") as handle:
        rows = [_clean(raw) for raw in csv.DictReader(handle)]
    problems = _problems(rows)
    if problems:
        print(f"{args.csv}: fix these rows first", *problems, sep="\n", file=sys.stderr)
        return 1
    args.out.write_text(render(rows, args.date), encoding="utf-8")
    print(f"{len(rows)} papers written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
